import assert from 'node:assert/strict';
import {parseInstallCsv,aggregateInstalls,decodeReport} from '../supabase/functions/google-downloads-sync/core.mjs';
const csv='Date,Package Name,Country,Daily User Installs\r\n2026-11-01,com.one,KR,2\r\n2026-11-01,com.one,US,0\r\n2026-11-02,com.one,KR,3\r\n';
const rows=parseInstallCsv(csv,'com.one');
assert.equal(aggregateInstalls(rows,'2026-11-01','2026-11-02').installs,5);
assert.equal(aggregateInstalls(rows,'2026-11-01','2026-11-02').complete,true);
assert.equal(aggregateInstalls(rows,'2026-10-31','2026-11-02').complete,false);
assert.equal(aggregateInstalls([],'2026-11-01','2026-11-02').installs,null);
assert.equal(aggregateInstalls(parseInstallCsv(csv.replace(/,2\r/,',0\r').replace(/,3\r/,',0\r'),'com.one'),'2026-11-01','2026-11-02').installs,0);
assert.equal(aggregateInstalls([...rows,...rows],'2026-11-01','2026-11-02').installs,5);
assert.throws(()=>aggregateInstalls([...rows,{...rows[0],count:7}],'2026-11-01','2026-11-02'));
assert.throws(()=>parseInstallCsv(csv.replace('com.one','com.other'),'com.one'));
assert.throws(()=>parseInstallCsv(csv.replace(',2\r',',-1\r'),'com.one'));
assert.throws(()=>parseInstallCsv(csv.replace('Daily User Installs','Daily Device Installs'),'com.one'));
assert.throws(()=>parseInstallCsv(csv.replace('2026-11-01','2026-11-99'),'com.one'));
assert.throws(()=>parseInstallCsv(csv.replace(',2\r',',\r'),'com.one'));
const quoted='Date,Package Name,Country,Daily User Installs,Note\n2026-11-01,com.one,KR,2,"a,b\nline"\n';
assert.equal(parseInstallCsv(quoted,'com.one')[0].count,2);
const bytes=Buffer.concat([Buffer.from([255,254]),Buffer.from(csv,'utf16le')]);
assert.equal(decodeReport(bytes),csv);
assert.throws(()=>parseInstallCsv('Date,Package Name,Country,Daily User Installs\n2026-11-01,com.one,KR,"2','com.one'));
console.log('Google CSV validation, deduplication, period and null checks passed');
